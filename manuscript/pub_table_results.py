#!/usr/bin/env python3
"""pub_table_results.py — main-text results statistics (Figures 3 and 4).

One diffable source-of-truth table for every number the Results section
quotes, drawn entirely from the frozen Stage 2 CSVs (``pub_stage2.py``,
2000 IAAFT/window at publication settings) that Figures 3 and 4 plot.
Nothing is hand-typed. Two blocks, mirroring the figures exactly:

  Fingerprints (Figure 3, tau=0): temperature, relative humidity,
  upwelling longwave, water vapor flux (3 m), each to d-excess and dD.

  Downwelling longwave lag structure (Figure 4): LW-down at every plotted
  lag -- d-excess at tau 0-3, dD at tau 0-2 (dD carries no tau=3, matching
  the plotted selection).

Per row: winter mean and peak transfer entropy as % of per-window
H(target), the peak date, and the fraction of windows above the per-window
IAAFT 95th percentile. Statistics use raw per-window values (no
presentation smoothing) over the truncated winter (window centers before
``pub_config.analysis_end``); windows above 100% of H are excluded per the
pre-stated rule and footnoted if any occur.

Outputs (LaTeX ``\\input`` whole; diff on regeneration):
    publication_output/table_results.tex
    publication_output/table_results.md   (author preview)

Usage:
    .venv/bin/python3 pub_table_results.py

Author: Matthew Rybecky
"""

from __future__ import annotations

import logging
from pathlib import Path
from typing import Dict, List, Tuple

import pandas as pd

from pub_config import PublicationConfig
from pub_labels import tau_of

logging.basicConfig(level=logging.INFO, format='%(levelname)s - %(message)s')
logger = logging.getLogger(__name__)

RESOLUTION_HOURS = 6   # base data cadence: tau index -> lag hours

# Figure 3 single-driver fingerprints (tau=0), both targets each.
FINGERPRINTS: List[Tuple[str, str]] = [
    ('Temperature', 'met_temp__t0'),
    ('Relative humidity', 'met_rh__t0'),
    ('Upwelling longwave', 'rad_lw_up__t0'),
    ('Water vapor flux (3 m)', 'flux_3m_h2o__t0'),
]
TARGETS = ['d_excess', 'dD']

# Figure 4 downwelling-longwave lag structure: the plotted lags per target
# (d-excess t0-t3, dD t0-t2 -- exactly the CROSS_SELECTIONS set).
LWDOWN: Dict[str, List[int]] = {
    'd_excess': [0, 1, 2, 3],
    'dD': [0, 1, 2],
}
LWDOWN_LABEL = 'Downwelling longwave'

TARGET_TEX = {'d_excess': 'd-excess', 'dD': '$\\delta$D'}
TARGET_MD = {'d_excess': 'd-excess', 'dD': 'dD'}


def entity_stats(base: Path, end: pd.Timestamp, target: str,
                 entity: str) -> Dict:
    """Raw per-window statistics for one entity on one target."""
    path = base / 'stage2' / target / f'stage2_{entity}.csv'
    df = pd.read_csv(path, parse_dates=['timestamp'])
    df = df[df['timestamp'] < end]
    over = int((df['pct_h'] > 100.0).sum())
    df = df[df['pct_h'] <= 100.0]
    peak_row = df.loc[df['pct_h'].idxmax()]
    return {'mean': df['pct_h'].mean(), 'peak': peak_row['pct_h'],
            'mean_bits': df['te_bits'].mean(), 'peak_bits': peak_row['te_bits'],
            'peak_date': peak_row['timestamp'],
            'n_sig': int(df['sig95'].sum()), 'n': len(df), 'n_over': over}


def gather(base: Path, end: pd.Timestamp) -> Tuple[List[Dict], List[Dict]]:
    """Fingerprint rows and LW-down rows, in figure order."""
    fp = []
    for label, entity in FINGERPRINTS:
        for target in TARGETS:
            fp.append({'label': label, 'lag_h': 0, 'target': target,
                       **entity_stats(base, end, target, entity)})
    lw = []
    for target in TARGETS:
        for tau in LWDOWN[target]:
            s = entity_stats(base, end, target, f'rad_lw_down__t{tau}')
            lw.append({'label': LWDOWN_LABEL, 'lag_h': tau * RESOLUTION_HOURS,
                       'target': target, **s})
    return fp, lw


def _tex_rows(rows: List[Dict], target_map: Dict) -> List[str]:
    """Body rows; the driver label is blank on repeats for readability."""
    out, prev = [], None
    for r in rows:
        key = (r['label'], r['lag_h'])
        label = r['label'] if key != prev else ''
        prev = key
        out.append(f"{label} & {r['lag_h']} & {target_map[r['target']]} & "
                   f"{r['mean']:.1f} ({r['mean_bits']:.2f}) & "
                   f"{r['peak']:.1f} ({r['peak_bits']:.2f}) & "
                   f"{r['peak_date']:%b %d} & {r['n_sig']}/{r['n']} \\\\")
    return out


def build_latex(fp: List[Dict], lw: List[Dict]) -> str:
    """The complete LaTeX table with the two labelled blocks."""
    n_over = sum(r['n_over'] for r in fp + lw)
    head = [
        '% Generated by TE_V1.0.0/pub_table_results.py from the Stage 2 CSVs.',
        '% Never hand-edit: rerun the script and diff.',
        '% sidewaystable (landscape): the seven-column table overruns the',
        '% portrait text width (author, 2026-07-19); rotating is loaded and',
        '% preferred by the agujournal2025 class.',
        '\\begin{sidewaystable}',
        '\\caption{Main-text transfer-entropy results: winter mean and peak '
        'transfer entropy in bits and as a percentage of per-window target '
        'entropy, and the fraction of windows above the per-window IAAFT '
        '95th percentile.$^{a}$}',
        '\\label{tab:results}', '\\centering',
        '\\begin{tabular}{l c l c c c c}', '\\hline',
        'Driver & Lag (h) & Target & Mean \\% $H$ (bits) & '
        'Peak \\% $H$ (bits) & Peak date & Sig.\\ windows \\\\', '\\hline',
        '\\multicolumn{7}{l}{\\textit{Single-driver fingerprints '
        '(Figure~\\ref{fig:fingerprints})}} \\\\',
    ]
    mid = ['\\hline',
           '\\multicolumn{7}{l}{\\textit{Downwelling-longwave lag structure '
           '(Figure~\\ref{fig:lwdown})}} \\\\']
    foot = ('$^{a}$ Statistics over the truncated winter (window centers '
            'before May 1); 30-day rolling windows; significance from 2000 '
            'source-only IAAFT surrogates per window.')
    if n_over:
        foot += (f' {n_over} window(s) exceeding 100\\% of target entropy '
                 'excluded per the pre-stated rule.')
    tail = ['\\hline',
            f'\\multicolumn{{7}}{{l}}{{\\footnotesize {foot}}} \\\\',
            '\\end{tabular}', '\\end{sidewaystable}']
    return '\n'.join(head + _tex_rows(fp, TARGET_TEX) + mid
                     + _tex_rows(lw, TARGET_TEX) + tail) + '\n'


def build_markdown(fp: List[Dict], lw: List[Dict]) -> str:
    """Author-preview mirror."""
    header = ['| Driver | Lag (h) | Target | Mean %H (bits) '
              '| Peak %H (bits) | Peak date | Sig. windows |',
              '| --- | --- | --- | --- | --- | --- | --- |']

    def md_rows(rows: List[Dict]) -> List[str]:
        out, prev = [], None
        for r in rows:
            key = (r['label'], r['lag_h'])
            label = r['label'] if key != prev else ''
            prev = key
            out.append(f"| {label} | {r['lag_h']} | {TARGET_MD[r['target']]} "
                       f"| {r['mean']:.1f} ({r['mean_bits']:.2f}) "
                       f"| {r['peak']:.1f} ({r['peak_bits']:.2f}) | "
                       f"{r['peak_date']:%b %d} | {r['n_sig']}/{r['n']} |")
        return out

    lines = ['# Table (main results) preview — from Stage 2 CSVs', '',
             '**Single-driver fingerprints (Figure 3)**', ''] + header
    lines += md_rows(fp)
    lines += ['', '**Downwelling-longwave lag structure (Figure 4)**', ''] + header
    lines += md_rows(lw)
    return '\n'.join(lines) + '\n'


def main() -> None:
    cfg = PublicationConfig()
    base = Path(cfg.output_base)
    fp, lw = gather(base, pd.Timestamp(cfg.analysis_end))
    (base / 'table_results.tex').write_text(build_latex(fp, lw))
    (base / 'table_results.md').write_text(build_markdown(fp, lw))
    logger.info(f"{len(fp)} fingerprint + {len(lw)} LW-down rows")
    for r in fp + lw:
        logger.info(f"  {r['label'][:22]:22s} lag{r['lag_h']:>2}h "
                    f"{TARGET_MD[r['target']]:8s} "
                    f"mean={r['mean']:5.1f}% ({r['mean_bits']:.2f}b) "
                    f"peak={r['peak']:5.1f}% ({r['peak_bits']:.2f}b) "
                    f"@ {r['peak_date']:%b %d} sig={r['n_sig']}/{r['n']}")
    logger.info(f"wrote {base}/table_results.{{tex,md}}")


if __name__ == '__main__':
    main()
